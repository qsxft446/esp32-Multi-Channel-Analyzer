#pragma once
#include <stdint.h>
#include "esp_err.h"

/* Генерация тактового сигнала для AD9226.
 *
 * ВАЖНО (урок прежнего опыта): настраиваем ОДИН РАЗ и больше
 * не трогаем в цикле. Никаких периодических вызовов ledc_update_duty
 * из задачи - именно они рвались при вытеснении задачи сетью и давали
 * мерцание светодиода. Аппаратный счётчик держит меандр сам.
 */
esp_err_t adc_clk_start(uint32_t freq_hz);

/* Смена частоты. Вызывать ТОЛЬКО при остановленном наборе:
 * реконфигурация таймера даёт короткий переходный процесс на CLK. */
esp_err_t adc_clk_set_freq(uint32_t freq_hz);

/* Настоящая частота CLK (что вышло, а не что просили). */
uint32_t  adc_clk_get_freq(void);

/* Записать в LCD_CAM источник и делитель такта модуля. Зовёт adc_cap
 * после сброса блока: при MCA_CLK_GEN_CAM этот же делитель даёт CLK
 * для АЦП, и без повторной записи сброс его бы остановил. */
void      adc_clk_cam_apply(void);
