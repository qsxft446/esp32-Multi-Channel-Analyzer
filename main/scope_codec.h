#pragma once
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* СЖАТИЕ ОСЦИЛЛОГРАММЫ БЕЗ ПОТЕРЬ для отдачи по WebSocket.
 *
 * Соседние отсчёты отличаются на единицы кодов (шум), поэтому передаются
 * разности по 4 бита. Поток полубайтов, старший полубайт байта первым:
 *   - первый отсчёт - 3 полубайта, 12 бит целиком;
 *   - дальше на отсчёт: полубайт = разность с предыдущим от -7 до 7
 *     (дополнительный код в 4 битах);
 *   - полубайт 8 (-8) - выход: следом 3 полубайта, 12 бит отсчёта целиком.
 * Нечётный хвост дополняется нулевым полубайтом - расшифровщик знает
 * число отсчётов и дальше не читает.
 * На модели сигнала прибора (шум 1-2 кода, до 20 000 имп/с) это 3.5-4
 * раза меньше, чем по 2 байта на отсчёт (tools/scopecodec.py - та же
 * схема, JS-расшифровщик - функция wdec на странице).
 *
 * Отсчёты - 12 бит (старшие биты отбрасываются). */

typedef struct {
    uint16_t prev;       /* предыдущий отсчёт            */
    bool     started;    /* первый отсчёт уже записан    */
    bool     half;       /* в acc ждёт старший полубайт  */
    uint8_t  acc;
} scodec_t;

/* Сжать сколько поместится: на отсчёт нужно не больше 2 байт выхода.
 * Возвращает число взятых отсчётов, *used - записано байт. Состояние
 * переносится между вызовами, так что поток можно резать на куски. */
size_t scodec_encode(scodec_t *s, const uint16_t *src, size_t n,
                     uint8_t *out, size_t cap, size_t *used);
/* Дописать недостающий полубайт в конце потока: 0 или 1 байт. */
size_t scodec_finish(scodec_t *s, uint8_t *out);
/* Расшифровать n отсчётов; возвращает сколько получилось (меньше n -
 * поток короче, чем нужно). */
size_t scodec_decode(const uint8_t *in, size_t len, uint16_t *dst, size_t n);
/* Самопроверка на приборе: случайное блуждание с выбросами и краями
 * 0/4095, сжатие кусками разной длины, расшифровка, сверка. */
bool   scodec_selftest(void);
