#pragma once
#include <stdint.h>
#include <stddef.h>

/* ПРОФИЛЬ РАБОТЫ ПРИБОРА.
 *
 * Появился после нескольких неудачных попыток объяснить замирания
 * страницы и потерянные чанки по догадкам. Задача одна: показать, ЧТО
 * происходило в момент потери чанка, а не рассуждать об этом.
 *
 * Всё измерение - это чтение счётчика тактов и обновление максимумов,
 * поэтому его можно держать включённым всегда.
 *
 * Главное здесь - журнал потерь: на каждую потерю пишется глубина
 * очереди, какой запрос в это время обслуживался и сколько он уже
 * длился. Если потери совпадают с запросами - виноват веб; если нет -
 * обработка или сам захват. */

/* Какой запрос обслуживается в данный момент. */
enum {
    PROF_EP_NONE = 0,
    PROF_EP_SPEC,        /* /spectrum */
    PROF_EP_SCOPE,       /* /scope    */
    PROF_EP_STAT,        /* /stat     */
    PROF_EP_CNT
};

/* Из задачи обработки, на каждый чанк:
 *  q_depth - сколько чанков ещё ждёт в очереди (16 из 16 = потери),
 *  wait_us - сколько задача ждала этот чанк,
 *  work_us - сколько заняла его обработка. */
void mca_prof_chunk(uint32_t q_depth, uint32_t wait_us, uint32_t work_us);

/* Из задачи обработки, когда счётчик потерь вырос. */
void mca_prof_loss(uint32_t lost_delta, uint32_t q_depth);

/* Вокруг обработчиков HTTP. */
void mca_prof_web_begin(int ep);
void mca_prof_web_end(int ep);

/* Раз в секунду из главной задачи: закрыть секунду и снять снимок. */
void mca_prof_tick_1s(void);

typedef struct {
    uint32_t chunks;              /* чанков за секунду                  */
    uint32_t q_max;               /* пиковая глубина очереди            */
    uint32_t wait_max_us;         /* самое долгое ожидание чанка        */
    uint32_t work_max_us;         /* самая долгая обработка чанка       */
    uint32_t busy_pm;             /* доля времени в обработке, промилле */
    uint32_t web_max_us[PROF_EP_CNT]; /* самый долгий запрос по видам   */
    uint32_t web_cnt[PROF_EP_CNT];    /* сколько запросов за секунду    */
    uint32_t lost_1s;             /* потеряно чанков за секунду         */
    uint32_t heap_now;            /* свободная внутренняя память        */
    uint32_t heap_min;            /* её минимум за всё время            */
    int32_t  rssi;               /* уровень сигнала WiFi, 0 - нет связи */
} mca_prof_t;

void mca_prof_get(mca_prof_t *out);

/* Журнал потерь: что происходило в момент потери. */
typedef struct {
    uint32_t t_ms;        /* время с включения, мс                      */
    uint32_t lost;        /* сколько чанков потеряно разом              */
    uint32_t q_depth;     /* глубина очереди в этот момент              */
    uint32_t web_us;      /* сколько к этому моменту длился запрос       */
    uint32_t work_us;     /* самая долгая обработка в эту секунду       */
    uint8_t  web_ep;      /* какой запрос обслуживался (PROF_EP_*)      */
} mca_prof_ev_t;

/* Последние события, свежие первыми. Возвращает сколько записано. */
size_t mca_prof_events(mca_prof_ev_t *out, size_t max);
