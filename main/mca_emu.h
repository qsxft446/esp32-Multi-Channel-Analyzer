#pragma once
#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"

/* Эмуляция MCA на последовательном порту UART0 (разъём UART/COM платы)
 * по бинарному протоколу shproto: программы на ПК, умеющие работать с
 * анализаторами на этом протоколе (например, BecqMoni), видят прибор как
 * такой анализатор. Пока эмуляция включена, консоль молчит: порт занят
 * протоколом. Подробности - в mca_emu.c и README. */

/* Загрузить настройку и, если эмуляция была включена, запустить её.
 * Вызывать после mca_settings_load() - NVS к этому моменту поднят. */
void      mca_emu_init(void);

/* 0 - выключить; иначе скорость порта из списка протокола. Сохраняется
 * в памяти прибора и действует сразу. */
esp_err_t mca_emu_set(uint32_t baud);

/* Текущая скорость, 0 - эмуляция выключена. */
uint32_t  mca_emu_baud(void);
