#pragma once
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

/* Диагностика тракта АЦП и осциллограмма.
 *
 * Разделение по стоимости:
 *  - счётчики потока и измеренная скорость считаются ВСЕГДА
 *    (это почти бесплатно и нужно, чтобы отличить "работает"
 *     от "молча ничего не делает");
 *  - побитовая статистика включается галочкой и считается
 *    по ОДНОМУ чанку раз в секунду, а не по каждому;
 *  - осциллограмма собирается только в режимах осциллографа.
 */

#define DIAG_NBITS 13       /* D0..D11 + OTR */
/* Окно осциллографа: до 32768 отсчётов, при 8 МГц это 4 мс. Буферы окна
 * (2 x 64 КБ) - в PSRAM: во внутреннюю память не влезают.
 *
 * Собирается ровно столько, сколько просит страница под развёртку
 * (mca_diag_set_scope_want), поэтому на коротких развёртках лишнего в
 * PSRAM не пишется. Раньше окно уменьшали до 8192 и переносили во
 * внутреннюю память, считая PSRAM причиной замираний обновления; главной
 * причиной оказались гармоники CLK АЦП в полосе WiFi (см. README). */
#define DIAG_SCOPE_LEN 32768
/* Предыстория до момента синхронизации: при самой длинной развёртке
 * фронт стоит почти на пятой части экрана. Берётся из нескольких
 * предыдущих буферов захвата, копия - один раз при срабатывании. */
#define DIAG_SCOPE_PRE 6144
/* Синхронизация по перепаду за столько отсчётов. Должно накрывать
 * фронт импульса: при 10 МГц 8 отсчётов = 0.8 мкс. */
#define DIAG_TRIG_SPAN 8

typedef struct {
    /* --- считается всегда --- */
    uint64_t chunks_total;
    uint64_t samples_total;
    uint32_t rate_measured;     /* отсчётов/с, замер за последнюю секунду */
    uint32_t rate_expected;     /* = частота CLK                          */
    int32_t  rate_error_pct;    /* отклонение, %                          */
    bool     data_flowing;      /* хоть что-то пришло за последнюю секунду*/

    /* --- только при включённой диагностике --- */
    bool     stats_valid;
    uint32_t bit_toggles[DIAG_NBITS];  /* переключений бита в чанке */
    uint16_t bit_always_1;             /* маска: бит всегда 1        */
    uint16_t bit_always_0;             /* маска: бит всегда 0        */
    uint16_t vmin, vmax;
    uint32_t vmean;
    uint32_t otr_count;                /* сколько раз взведён OTR    */
    uint32_t analyzed_samples;
} mca_diag_t;

typedef enum {
    DIAG_SCOPE_OFF    = 0,  /* снимок не нужен: спектр, импульсы          */
    DIAG_SCOPE_AUTO   = 1,  /* по фронту, а без фронта - свободный пуск   */
    DIAG_SCOPE_NORMAL = 2,  /* ждущий: только по фронту, держит последний */
} diag_scope_mode_t;

void mca_diag_init(void);
void mca_diag_set_enabled(bool en);
bool mca_diag_get_enabled(void);

/* Вызывается из DSP-задачи на каждый чанк. */
void mca_diag_feed(const uint16_t *data, size_t n, diag_scope_mode_t sm);
/* Разрыв потока (потерян чанк): недособранное окно больше не
 * непрерывно, начинаем заново. Вызывать из той же задачи, что feed. */
void mca_diag_flush(void);

void mca_diag_tick_1s(uint32_t expected_rate);
void mca_diag_get(mca_diag_t *out);

/* Кусок последней осциллограммы длиной до max отсчётов, начиная за
 * pre отсчётов до момента синхронизации (или с начала окна, если
 * столько нет или снимок без синхронизации). trig_pos - индекс момента
 * синхронизации В ОТДАННОМ КУСКЕ, -1 при свободном пуске; rise -
 * перепад, на котором сработала синхронизация; age_ms - возраст
 * снимка, -1 если снимков ещё не было; full_len - длина всего окна;
 * amp - высота показанного импульса над базой, коды АЦП (-1 - не
 * мерилась, например свободный пуск); rej - сколько импульсов отброшено
 * фильтром амплитуды с прошлого кадра. */
size_t  mca_diag_get_scope(uint16_t *dst, size_t max, size_t pre,
                           int32_t *trig_pos, int32_t *rise,
                           int32_t *age_ms, size_t *full_len,
                           int32_t *amp, uint32_t *rej);
/* Сколько отсчётов нужно странице (развёртка с запасом): столько после
 * предыстории и собирается. */
void    mca_diag_set_scope_want(size_t n);
/* Синхронизация по амплитуде: кадр публикуется, только если высота
 * импульса над базой в [lo, hi] кодов. hi <= 0 - фильтр выключен. */
void    mca_diag_set_amp_window(int32_t lo, int32_t hi);
/* Уровень синхронизации: перепад вверх за DIAG_TRIG_SPAN отсчётов,
 * коды АЦП. */
void    mca_diag_set_trig_level(int32_t lvl);
int32_t mca_diag_get_trig_level(void);
