#pragma once
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* ИСТОРИЯ CPS: кольцо односекундных отсчётов набора спектра в PSRAM.
 *
 * Раз в секунду главная задача кладёт сюда, сколько событий попало в
 * спектр и сколько за эту секунду реально шёл набор (без потерянных
 * чанков). Пока набор стоит, отсчёты не пишутся - на графике разрыв.
 * Страница (мониторинг на вкладке «Спектр») дочитывает новые отсчёты по
 * номеру и сама усредняет их по интервалу. Кольцо копится независимо от
 * того, открыта ли страница. */

#define MCA_HIST_LEN 21600      /* 6 ч по 1 с */

typedef struct __attribute__((packed)) {
    uint32_t end_ds;   /* конец секунды: время с включения прибора, 0.1 с */
    uint32_t counts;   /* событий в спектре за эту секунду                */
    uint16_t dur_ms;   /* сколько из неё шёл набор, мс                   */
} mca_hist_sample_t;   /* 10 байт: 6 ч - 216 КБ */

bool   mca_hist_init(void);
/* Из главной задачи, раз в секунду, только если dur_ms > 0. */
void   mca_hist_push(uint32_t counts, uint32_t dur_ms);
/* Очистить и сменить эпоху (страница по ней понимает, что история новая). */
void   mca_hist_clear(void);
/* Отсчёты начиная с номера from (меньше старейшего или больше
 * следующего - со старейшего), не больше max. *first - номер out[0],
 * *next - номер будущего отсчёта, *epoch - эпоха истории (случайная при
 * включении и новая после очистки). Возвращает число скопированных. */
size_t mca_hist_copy(uint32_t from, mca_hist_sample_t *out, size_t max,
                     uint32_t *first, uint32_t *next, uint32_t *epoch);
